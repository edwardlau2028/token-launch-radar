// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// every pre-token protocol below the watchlist floor that is rankable: the early rows the radar
// exists to find. A protocol is pre-token when its record carries no token (no market cap, no
// CoinGecko id, no symbol); the live-token protocols are kept apart in their own view, shown with
// the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The base multiple is not a constant
// picked by hand: it is the median market-cap-to-TVL ratio of the live-token protocols in the same
// category, computed from this snapshot at run time (categories with fewer than five live samples
// fall back to the overall median). The rest is one function of the protocol's own record:
//
//   multiple   = median(mcap_usd / tvl_usd) over live-token protocols, same category if it has
//                at least 5 samples, else over all live-token protocols with a market cap
//   growth     = clamp(change_7d, -50, 100) per cent; unknown growth counts as 0
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = MATURITY_FLOOR + (1 - MATURITY_FLOOR) x min(1, ln(1 + age_days) / ln(1 + 1095))
//                age_days unknown: the snapshot's median age over all protocols that carry one
//   breadth    = 1 + BREADTH_PER_CHAIN x min(chains - 1, 8)
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard
// prints the multiples it used, so a reader can check the arithmetic.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

